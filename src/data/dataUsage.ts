/** 상태·출처별 건수 — 화면 머리말용 */
export function usageSummary(items: UsageItem[]) {
  const by = (f: (i: UsageItem) => string) => items.reduce<Record<string, number>>((m, i) => ({ ...m, [f(i)]: (m[f(i)] ?? 0) + 1 }), {})
  return { total: items.length, byState: by((i) => i.state), byOrigin: by((i) => i.origin) }
}
